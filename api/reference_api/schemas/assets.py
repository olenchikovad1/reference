"""Файлы: что отдаётся наружу."""

from pydantic import BaseModel

class DerivativeOut(BaseModel):
    """Ступень с ФАКТИЧЕСКИМИ размерами.

    Заявленный размер — только длинная сторона; короткую угадывать нельзя, по
    ней считается перевод сантиметров в пиксели.
    """

    name: str
    width: int
    height: int
    #: Ступень оказалась копией оригинала: он был мельче неё.
    is_copy: bool


class AssetOut(BaseModel):
    #: Имя по содержимому. Тот же файл, загруженный дважды, даёт тот же ответ.
    digest: str
    name: str
    content_type: str
    width: int
    height: int
    #: Ступени, готовые к выдаче. Оригинал в этот список не входит: он в браузер
    #: не уходит никогда и достаётся только на выгрузке техпакета.
    derivatives: list[DerivativeOut]
    #: Файл уже лежал: вторая загрузка места не заняла.
    reused: bool

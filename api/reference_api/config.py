"""Настройки сервиса: один типизированный объект, проверяемый при старте.

Все значения приходят из окружения. Умолчаний для адресов и ключей нет
сознательно: сервис, поднявшийся с выдуманным адресом базы, падает через час в
непонятном месте, а не в момент запуска.
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Всё, что сервис берёт снаружи. Обязательное отделено от необязательного."""

    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    # Обязательное: без этого сервис смысла не имеет и подниматься не должен.
    database_url: str
    s3_endpoint: str
    s3_bucket: str
    s3_access_key: str
    s3_secret_key: str

    # Путь к тому файлового пространства. Исходники изделий лежат здесь, а не в
    # объектном хранилище (решение 0002).
    files_volume_path: str
    # Описания изделий: тот же принцип, отдельный том только на чтение.
    fixtures_path: str
    #: Производные, которые пересчитываются сами: векторы слов словаря. Свой
    #: том на запись — том файлов только на чтение.
    cache_path: str = "/srv/reference/cache"
    embedding_model_path: str
    #: Автотеги (US-0482): слова — первые `tag_words` существительных
    #: частотного словаря по частоте, каждое в фразе `tag_template`. Замер
    #: (prints.yaml, measured_words), предварительно: на всём словаре первой
    #: на танках встаёт редкая «танка», из первых 10 000 она выпадает, а
    #: лишних сильных у 10 000 меньше, чем у 3 000 и 5 000. Шаблон «фото: {}»
    #: ничего не меняет.
    tag_words: int = 10000
    tag_template: str = "{}"
    #: Сильный тег — не слабее этой доли от самого сильного. Предварительно:
    #: 0.2 и 0.25 дают один F1, у 0.2 ожидаемых среди сильных больше.
    tag_strong_share: float = 0.2
    # Пороги узнавания. Предварительные: подбираются на наборе пар.
    # Умолчания равны измеренным на наборе пар, а не взятым на глаз: машина
    # без .env иначе молча получает непроверенный порог. 1.0 у «похожей»
    # означает выключено — на наших принтах уровень не подтвердился.
    similarity_same: float = 0.91
    similarity_close: float = 1.0
    #: Порог похожести НАДПИСИ — триграммная доля, не косинус. Природа у
    #: них разная, и сводить их в одно число нельзя (решение 0010).
    #: 0.3 предварительно: на замере несвязанные слоганы дали ровно 0.0,
    #: а близкие — 0.33 и выше.
    slogan_close: float = 0.3

    # Платформа. На базовом стенде приложение поднимается без неё (решение 0006),
    # поэтому значения необязательные — но как только появится первый маршрут с
    # объявлением права, они станут обязательными.
    platform_core_url: str | None = None
    platform_jwks_url: str | None = None
    platform_app_code: str = "reference"

    s3_region: str = "ru-central1"
    amqp_url: str | None = None
    log_level: str = "INFO"

    # Префикс, под которым приложение живёт в платформе. В разработке он
    # отличается от боевого намеренно: так зашитый корень виден до выкладки.
    base_path: str = "/reference/api"


@lru_cache
def settings() -> Settings:
    """Один экземпляр на процесс. Чтение окружения — не то, что делают в цикле."""
    return Settings()
